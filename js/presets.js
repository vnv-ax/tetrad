  function typography(src) {
    let t = src.replace(/\r\n?/g, "\n");
    t = t.replace(/\.\.\./g, "…");
    t = t.replace(/ -- /g, " — ").replace(/(\s)-(\s)/g, "$1—$2");
    t = t.replace(/[ \t]+([,.;:!?…])/g, "$1");
    t = t.replace(/([а-яёa-z],)([а-яёА-ЯЁA-Z])/g, "$1 $2");
    t = t.replace(/ {2,}/g, " ");
    let open = true;
    t = t.replace(/["“”„]/g, () => (open = !open) ? "»" : "«");
    return t;
  }
  function sentenceCase(src) {
    return src.toLowerCase().replace(/(^|[.!?…]\s+)([\p{Ll}])/gu, (_m, p, c) => p + c.toUpperCase());
  }
  function titleCase(src) {
    return src.toLowerCase().replace(/(^|[\s\-—«"([.,:])([\p{Ll}])/gu, (_m, p, c) => p + c.toUpperCase());
  }
  function joinLines(p) {
    const lines = p.split("\n").map(l => l.trim()).filter(Boolean);
    let out = "";
    for (const line of lines) {
      if (!out) {
        out = line;
        continue;
      }
      if (/-\u00ad?$/.test(out) && /^[a-zа-яё]/i.test(line)) out = out.replace(/-\u00ad?$/, "") + line; else out += " " + line;
    }
    return out;
  }
  function joinParagraphs(src) {
    return src.replace(/\r\n?/g, "\n").split(/\n{2,}/).map(p => joinLines(p)).join("\n\n");
  }
  function stripHtml(src) {
    const el = document.createElement("textarea");
    el.innerHTML = src.replace(/<script[\s\S]*?<\/script>/gi, "").replace(/<style[\s\S]*?<\/style>/gi, "");
    return el.value.replace(/<br\s*\/?>/gi, "\n").replace(/<\/(p|div|li|h[1-6]|tr)>/gi, "\n").replace(/<[^>]+>/g, "").replace(/ {2,}/g, " ").replace(/\n{3,}/g, "\n\n").trim();
  }
  function stripMarkdown(src) {
    return src.replace(/```[\s\S]*?```/g, m => m.replace(/```\w*\n?/g, "")).replace(/!\[([^\]]*)\]\([^)]*\)/g, "$1").replace(/\[([^\]]*)\]\([^)]*\)/g, "$1").replace(/^\s{0,3}#{1,6}\s+/gm, "").replace(/^\s{0,3}>\s?/gm, "").replace(/^\s{0,3}([-*_]\s*){3,}\s*$/gm, "").replace(/(\*\*\*|\*\*|\*|__|_|~~)/g, "").replace(/`/g, "").replace(/^\s*[-+*]\s+/gm, "").replace(/^\s*\d+\.\s+/gm, "");
  }
  function extract(re, src) {
    const out = [ ...new Set(src.match(re) || []) ];
    return out.join("\n");
  }
